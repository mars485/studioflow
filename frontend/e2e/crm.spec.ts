import {expect, test} from '@playwright/test';

test('registration through follow-up survives reload', async ({page}) => {
  const stamp = Date.now();
  const deal = `E2E deal ${stamp}`;
  await page.goto('/');
  if (await page.getByRole('button', {name: 'Повторить'}).isVisible()) await page.getByRole('button', {name: 'Повторить'}).click();
  await page.getByRole('button', {name: 'Создать аккаунт'}).click();
  await page.getByLabel('Ваше имя').fill('E2E');
  await page.getByLabel('Email').fill(`e2e-${stamp}@example.com`);
  await page.getByLabel('Пароль').fill(`TestPassword-${stamp}`);
  await page.getByRole('button', {name: 'Зарегистрироваться'}).click();
  await page.getByRole('button', {name: 'Настройки'}).click();
  await page.getByLabel('Название новой студии').fill(`E2E studio ${stamp}`);
  await page.getByRole('button', {name: 'Создать студию'}).click();
  await page.getByRole('button', {name: 'CRM', exact: true}).click();
  await page.getByRole('button', {name: 'Управление воронками'}).click();
  const pipelineSettings = page.getByRole('dialog', {name: 'Управление воронками'});
  await pipelineSettings.getByLabel('Новая воронка').fill(`E2E воронка ${stamp}`);
  await pipelineSettings.getByRole('button', {name: 'Создать воронку'}).click();
  await expect(page.getByRole('combobox', {name: 'Воронка'})).toHaveValue(/.+/);
  await expect(pipelineSettings.getByRole('button', {name: `Отключить E2E воронка ${stamp}`})).toBeVisible();
  await pipelineSettings.getByRole('button', {name: `Отключить E2E воронка ${stamp}`}).click();
  await expect(pipelineSettings.getByRole('button', {name: `Включить E2E воронка ${stamp}`})).toBeVisible();
  await pipelineSettings.getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('button', {name: 'Настроить стадии'}).click();
  const settings = page.getByRole('dialog', {name: 'Настройка стадий'});
  await settings.getByLabel('Новый этап').fill(`E2E этап ${stamp}`);
  await settings.getByRole('button', {name: 'Добавить этап'}).click();
  await expect(settings.getByRole('button', {name: `Выше E2E этап ${stamp}`})).toBeVisible();
  await settings.getByRole('button', {name: `Выше E2E этап ${stamp}`}).click();
  await expect(page.locator('.kanbanCol').nth(3).locator('.colHead b')).toHaveText(`E2E этап ${stamp}`);
  await settings.getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('button', {name: 'Новая сделка'}).click();
  const form = page.getByRole('dialog', {name: 'Новая сделка'});
  await form.getByLabel('Название сделки').fill(deal);
  await form.getByLabel('Название клиента').fill(`E2E client ${stamp}`);
  await form.getByLabel('Ответственный').selectOption({index: 1});
  await form.getByRole('button', {name: 'Сохранить сделку'}).click();
  const card = page.getByRole('article', {name: `Открыть ${deal}`});
  await expect(card).toBeVisible();
  await expect(card).toContainText('Ответственный: E2E');
  await card.click();
  await page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: `E2E client ${stamp}`}).click();
  const company = page.getByRole('dialog', {name: 'Компании'});
  await expect(company.getByRole('button', {name: deal})).toBeVisible();
  await company.getByLabel('Рабочий телефон').fill('+7 900 000-00-00');
  await company.getByRole('button', {name: 'Сохранить компанию'}).click();
  await expect(company.getByLabel('Рабочий телефон')).toHaveValue('+7 900 000-00-00');
  await company.getByRole('button', {name: 'Добавить контакт'}).click();
  const contacts = page.getByRole('dialog', {name: 'Контакты'});
  await contacts.getByLabel('Имя').fill('Мария');
  await contacts.getByLabel('Фамилия').fill('Иванова');
  await contacts.getByRole('button', {name: 'Сохранить контакт'}).click();
  await expect(contacts.getByRole('button', {name: 'Иванова Мария'})).toBeVisible();
  await contacts.getByRole('button', {name: 'Закрыть'}).click();
  await card.click();
  await page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: 'Редактировать'}).click();
  await page.getByRole('dialog', {name: 'Редактирование сделки'}).getByLabel('Связанный контакт').selectOption({label: 'Иванова Мария'});
  await page.getByRole('dialog', {name: 'Редактирование сделки'}).getByRole('button', {name: 'Сохранить сделку'}).click();
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: 'Иванова Мария'})).toBeVisible();
  await page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: 'Закрыть'}).click();
  const stage = page.locator('.kanbanCol').nth(1);
  await card.dragTo(stage);
  await expect(stage.getByRole('article', {name: `Открыть ${deal}`})).toBeVisible();
  await card.click();
  const drawer = page.getByRole('dialog', {name: 'Карточка сделки'});
  await expect(drawer.getByText(/Стадия: .* → /)).toBeVisible();
  await drawer.getByLabel('Дата и время').fill('2026-12-01T16:30');
  await drawer.getByLabel('Что сделать').selectOption('call');
  await drawer.getByLabel('Комментарий').fill('E2E follow-up');
  await drawer.getByRole('button', {name: 'Сохранить follow-up'}).click();
  await expect(drawer.getByRole('status')).toContainText('сохранён');
  await drawer.getByLabel('Новая заметка').fill('E2E разговор с клиентом');
  await drawer.getByRole('button', {name: 'Добавить в историю'}).click();
  await expect(drawer.getByText('E2E разговор с клиентом')).toBeVisible();
  await page.reload();
  await page.getByRole('article', {name: `Открыть ${deal}`}).click();
  await page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: `E2E client ${stamp}`}).click();
  await expect(page.getByRole('dialog', {name: 'Компании'}).getByLabel('Рабочий телефон')).toHaveValue('+7 900 000-00-00');
  await page.getByRole('dialog', {name: 'Компании'}).getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('article', {name: `Открыть ${deal}`}).click();
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: 'Иванова Мария'})).toBeVisible();
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByLabel('Комментарий')).toHaveValue('E2E follow-up');
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByText('E2E разговор с клиентом')).toBeVisible();
  const reopened = page.getByRole('dialog', {name: 'Карточка сделки'});
  await reopened.getByLabel('Итог контакта').fill('E2E контакт завершён');
  await reopened.getByRole('button', {name: 'Отметить follow-up выполненным'}).click();
  await expect(reopened.getByText('E2E контакт завершён')).toBeVisible();
  await page.reload();
  await page.getByRole('article', {name: `Открыть ${deal}`}).click();
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByText('E2E контакт завершён')).toBeVisible();
  await expect(page.getByRole('dialog', {name: 'Карточка сделки'}).getByRole('button', {name: 'Отметить follow-up выполненным'})).toHaveCount(0);
});
