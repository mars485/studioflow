import {expect, test} from '@playwright/test';

test('won deal → project → task → archive persists', async ({page}) => {
  await page.goto('/');
  await page.evaluate(async () => {
    const post = async (path: string, data: unknown) => {
      const response = await fetch(`/api/v1${path}`, {method: 'POST', headers: {'Content-Type': 'application/json', 'X-StudioFlow-Request': '1'}, body: JSON.stringify(data)});
      if (!response.ok) throw new Error(await response.text());
      return response.json();
    };
    const stamp = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
    await post('/auth/register', {email: `${stamp}@example.com`, password: 'Project-E2E-password123', first_name: 'Project E2E'});
    const workspace = await post('/workspaces', {name: 'Project E2E'});
    const base = `/workspaces/${workspace.id}`;
    const client = await post(`${base}/clients`, {name: 'Клиент проекта'});
    const contact = await post(`${base}/contacts`, {first_name: 'Мария', client_ids: [client.id]});
    const pipelines = await (await fetch(`/api/v1${base}/pipelines`)).json();
    const won = pipelines[0].stages.find((stage: {stage_type: string}) => stage.stage_type === 'WON');
    await post(`${base}/deals`, {title: 'Выигранный сайт', client_id: client.id, contact_id: contact.id,
      pipeline_id: pipelines[0].id, stage_id: won.id, amount: '65000.25'});
  });
  await page.reload();
  await page.getByRole('button', {name: 'Проекты', exact: true}).click();
  await page.getByRole('button', {name: 'Новый проект'}).click();
  const form = page.getByRole('dialog', {name: 'Новый проект'});
  await form.getByLabel('Сделка-источник').selectOption({label: 'Выигранный сайт'});
  await form.getByRole('button', {name: 'Создать проект'}).click();
  await page.getByRole('button', {name: 'Выигранный сайт', exact: true}).click();
  const drawer = page.getByRole('dialog', {name: 'Карточка проекта'});
  await expect(drawer.getByText('Контакты: Мария')).toBeVisible();
  await drawer.getByRole('tab', {name: 'Порядок работ'}).click();
  await drawer.getByLabel('Новый этап работ').fill('Дизайн E2E');
  await drawer.getByRole('button', {name: 'Добавить этап работ'}).click();
  await drawer.getByLabel('Начало этапа Дизайн E2E').fill('2026-11-01');
  await drawer.getByLabel('Окончание этапа Дизайн E2E').fill('2026-11-10');
  await drawer.getByLabel('Состояние этапа Дизайн E2E').selectOption('ACTIVE');
  await drawer.getByRole('button', {name: 'Сохранить этап Дизайн E2E'}).click();
  await expect(drawer.getByRole('heading', {name: 'Дизайн E2E · В работе'})).toBeVisible();
  await drawer.getByLabel('Название шаблона плана').fill('Типовой сайт E2E');
  await drawer.getByRole('button', {name: 'Сохранить план как шаблон'}).click();
  await expect(drawer.getByLabel('Название шаблона плана')).toHaveValue('');
  await drawer.getByRole('button', {name: 'Закрыть'}).click();
  await expect(page.getByText('Шаблоны проектов (1)', {exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Новый проект'}).click();
  await form.getByLabel('Название проекта').fill('Копия плана E2E');
  await form.getByLabel('Клиент проекта').selectOption({label: 'Клиент проекта'});
  await form.getByLabel('Шаблон проекта').selectOption({label: 'Типовой сайт E2E'});
  await form.getByLabel('Начало проекта по шаблону').fill('2027-01-01');
  await form.getByRole('button', {name: 'Создать проект'}).click();
  await page.getByRole('button', {name: 'Копия плана E2E', exact: true}).click();
  await drawer.getByRole('tab', {name: 'Гант', exact: true}).click();
  await expect(drawer.getByRole('img', {name: 'Дизайн E2E: 2027-01-01 — 2027-01-10'})).toBeVisible();
  await drawer.getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('button', {name: 'Выигранный сайт', exact: true}).click();
  await drawer.getByRole('tab', {name: 'Гант', exact: true}).click();
  await expect(drawer.getByRole('img', {name: 'Дизайн E2E: 2026-11-01 — 2026-11-10'})).toBeVisible();
  await drawer.getByRole('tab', {name: /Задачи/}).click();
  await drawer.getByLabel('Новая задача проекта').fill('Подготовить смету');
  await drawer.getByRole('button', {name: 'Добавить задачу'}).click();
  await expect(drawer.getByText('Подготовить смету', {exact: true})).toBeVisible();
  await drawer.getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('button', {name: 'Задачи', exact: true}).click();
  await expect(page.getByText('Подготовить смету', {exact: true})).toBeVisible();
  await page.reload();
  await page.getByRole('button', {name: 'Проекты', exact: true}).click();
  await page.getByRole('button', {name: 'Выигранный сайт', exact: true}).click();
  await drawer.getByRole('tab', {name: 'Порядок работ'}).click();
  await expect(drawer.getByLabel('Окончание этапа Дизайн E2E')).toHaveValue('2026-11-10');
  await drawer.getByRole('tab', {name: 'Общие', exact: true}).click();
  await drawer.getByRole('button', {name: 'В архив', exact: true}).click();
  await expect(drawer.getByRole('button', {name: 'Вернуть из архива'})).toBeVisible();
  await drawer.getByRole('button', {name: 'Закрыть'}).click();
  await page.getByRole('button', {name: 'Архив', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Выигранный сайт', exact: true})).toBeVisible();
});
