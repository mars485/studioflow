import {randomUUID} from 'node:crypto';
import {expect, test} from '@playwright/test';

test('one-time server token accepts an idempotent lead and stops after revocation', async ({page, request}) => {
  await page.goto('/');
  await page.evaluate(async () => {
    const post = async (path: string, data: unknown) => {
      const response = await fetch(`/api/v1${path}`, {method: 'POST', headers: {'Content-Type': 'application/json', 'X-StudioFlow-Request': '1'}, body: JSON.stringify(data)});
      if (!response.ok) throw new Error(await response.text());
      return response.json();
    };
    const stamp = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
    await post('/auth/register', {email: `${stamp}@example.com`, password: 'Integration-E2E-password123', first_name: 'Integration E2E'});
    await post('/workspaces', {name: 'Integration E2E'});
  });
  await page.reload();
  await page.getByRole('button', {name: 'Интеграции', exact: true}).click();
  const outgoing = page.getByRole('region', {name: 'Исходящие webhooks'});
  await outgoing.getByLabel('Назначение webhook').selectOption('e2e-only');
  await outgoing.getByRole('button', {name: 'Создать подписку webhook'}).click();
  await expect(outgoing.getByLabel('Ключ подписи webhook')).not.toHaveValue('');
  await outgoing.getByRole('button', {name: 'Скрыть ключ webhook'}).click();
  await page.getByLabel('Название интеграции').fill('ITG server E2E');
  await page.getByRole('button', {name: 'Создать интеграционный токен'}).click();
  const secretField = page.getByLabel('Новый API-токен');
  await expect(secretField).toHaveValue(/^sf_lead_/);
  const secret = await secretField.inputValue();
  const headers = {'Authorization': `Bearer ${secret}`, 'X-StudioFlow-Request': '1'};
  const data = {request_key: randomUUID(), title: 'Заявка через токен E2E', company_name: 'Клиент интеграции', contact_first_name: 'Мария', email: 'integration-e2e@example.com', source: 'ITG E2E'};
  // The standalone API request context has no browser session cookies.
  const created = await request.post('/api/v1/integrations/leads', {headers, data});
  expect(created.status()).toBe(201);
  const receipt = await created.json();
  const replay = await request.post('/api/v1/integrations/leads', {headers, data});
  expect(replay.status()).toBe(200);
  expect((await replay.json()).deal_id).toBe(receipt.deal_id);
  await page.getByRole('button', {name: 'Скрыть секрет'}).click();
  await page.getByRole('button', {name: 'Обновить интеграции'}).click();
  await page.getByRole('button', {name: 'Открыть заявку Заявка через токен E2E'}).click();
  const drawer = page.getByRole('dialog', {name: 'Карточка сделки'});
  await expect(drawer).toContainText('Заявка через токен E2E');
  await expect(drawer).toContainText('Мария');
  await drawer.getByRole('button', {name: 'Закрыть'}).click();
  const csvDownload = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Скачать CSV'}).click();
  const exported = await csvDownload;
  expect(exported.suggestedFilename()).toBe('studioflow-deals.csv');
  const stream = await exported.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks).toString('utf8')).toContain('Заявка через токен E2E');
  await page.getByRole('button', {name: 'Интеграции', exact: true}).click();
  await expect(secretField).not.toBeVisible();
  await expect(outgoing.getByText(/deal.created · PENDING · попыток: 0/)).toHaveCount(1);
  await outgoing.getByRole('button', {name: 'Отключить webhook e2e-only'}).click();
  await expect(outgoing.getByText(/deal.created · CANCELLED/)).toHaveCount(1);
  page.once('dialog', dialog => void dialog.accept());
  await page.getByRole('button', {name: 'Отозвать токен ITG server E2E'}).click();
  await expect(page.getByText(/^Отозван · Последний приём:/)).toBeVisible();
  const denied = await request.post('/api/v1/integrations/leads', {headers, data: {...data, request_key: randomUUID()}});
  expect(denied.status()).toBe(401);
  await page.getByRole('button', {name: 'Аналитика', exact: true}).click();
  const metrics = page.getByRole('region', {name: 'Показатели продаж'});
  await expect(metrics.getByText('Открытые сделки', {exact: true}).locator('..').getByText('1', {exact: true})).toBeVisible();
  await expect(page.getByText('В выбранном периоде сделок нет.')).not.toBeVisible();
  await page.getByRole('button', {name: 'Главная', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Главная', exact: true})).toBeVisible();
  await expect(page.getByRole('region', {name: 'Показатели продаж'})).toBeVisible();
});
